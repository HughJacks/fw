import os, sys
sys.path.insert(0, "."); import fwtest as F
from fwtest import check, same, blk, QUIT as Q, UNDO as Z, REDO as Y, UP, ESC, MENU
S = F.use_store("t/newquote.json", clean=True)
HOST, CH = "20261001T100000-b000", "20261001T100000-b001"
OLD, CO = "20261001T100000-a000", "20261001T100000-a001"
F.write_store([blk(HOST, [CH], "host"), blk(CH, "host text"),
               blk(OLD, [CO], "old note"), blk(CO, "old text")], [HOST, OLD])
def data(): return S.load_data()
def entries(): return S.entry_ids(data())
def text(i): return S.own_text(S.index(data()), i)
def titled(t): return next((b["id"] for b in data()["blocks"] if b.get("title") == t), None)
def quotes(i): return [S.quoted(S.index(data()).get(k)) for k in S.children(S.index(data())[i]) if S.quoted(S.index(data()).get(k))]
def bar(t): return t.row(t.scr.lines - 1)

f = F.fw("host")
f.key(F.ENTER, "/", F.ENTER)
check("the quote search has a + new entry row", "+ new pericope" in f.text(), f.text())
f.key("groceries")
check("  titled with what you typed", "+ new pericope “groceries”" in f.text(), f.text())
f.key(F.ENTER)
new = titled("groceries")
check("picking it makes the entry", new in entries(), entries())
check("  quotes it here", [q[0] for q in quotes(HOST)] == [new], quotes(HOST))
check("  and steps into it", "host ›" in bar(f), bar(f))
f.key("milk"); f.settle()
same("typing writes the new entry", text(new), "milk")
f.key(Q)
check("^Q comes back, the quote shows it", "milk" in f.text() and "host ›" not in bar(f), f.text())
f.key(Z); f.settle()
check("^Z takes back the quote and the entry", not quotes(HOST) and new not in S.index(data()), (quotes(HOST), entries()))
f.key(Y); f.settle()
check("  ^Y brings both back", [q[0] for q in quotes(HOST)] == [new] and text(new) == "milk", (quotes(HOST), text(new)))
f.key(Q, ESC); f.done()

g = F.fw("host")
g.key(F.ENTER, "/", F.ENTER, UP, F.ENTER)
check("an untitled new entry: stepped into", "host ›" in bar(g), bar(g))
before = set(entries())
g.key(Q); g.settle()
check("  left empty, it's gone when you come back", len(entries()) == len(before) - 1 and len(quotes(HOST)) == 1, (entries(), quotes(HOST)))
check("  and so is its quote, on screen", "nothing written, no new pericope" in bar(g), bar(g))
n = len(data()["blocks"])
g.key(Y); g.settle()
check("  it never happened: ^Y doesn't bring it back", len(quotes(HOST)) == 1 and len(data()["blocks"]) == n, quotes(HOST))
g.key(Q, ESC); g.done()

h = F.fw("host")
n = len(data()["blocks"])
h.key(F.ENTER, "/", F.ENTER, UP, F.ENTER, Z); h.settle()
check("^Z in the empty new entry steps back and drops it too", "host ›" not in bar(h) and len(data()["blocks"]) == n, (bar(h), len(data()["blocks"]), n))
h.key(Q, ESC); h.done()

p = F.fw("old note")
p.key(MENU, "and open")
check("Turn into a quote and open it is in the menu", "Turn into a quote and open it" in p.text(), p.text())
p.key(F.ENTER)
popped = next(r for r in entries() if r not in (HOST, OLD, titled("groceries")))
check("  it pops the block out and steps into it", "old note ›" in bar(p) and text(popped) == "old text", (bar(p), text(popped)))
p.key(Q)
check("  ^Q comes back to the quote of it", [q[0] for q in quotes(OLD)] == [popped] and "old note ›" not in bar(p), quotes(OLD))
p.key(Q, ESC); p.done()
check("no drafts left behind", not [x for x in os.listdir(F.DEV) if x.startswith(".fw-")], os.listdir(F.DEV))
F.report("NEWQUOTE")
